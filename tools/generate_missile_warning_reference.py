#!/usr/bin/env python3
"""Capture native hostile-missile HUD positions, including clipping and word wrapping."""
import argparse
import hashlib
from pathlib import Path
import random
import struct
import sys
from generate_resource_directory import IMAGE_SHA256

workspace = argparse.ArgumentParser(description=__doc__)
workspace.add_argument('workspace', type=Path)
root = workspace.parse_args().workspace.resolve()
sys.path.insert(0, str(root / 'tools'))
from trace_hidden_commands import Harness
from unicorn import UC_HOOK_CODE

image = (root / 'analysis/unpacked/image.bin').read_bytes()
assert hashlib.sha256(image).hexdigest() == IMAGE_SHA256
native = Harness(image)
native.write(0x9c4a, image[0x944a:0x964a])
points = []
covered = True

def return_from_call(cpu):
    sp = native.getreg('SP')
    native.setreg('IP', int.from_bytes(cpu.mem_read(native.STACK + sp, 2), 'little'))
    native.setreg('SP', sp + 2)

def hook(cpu, address, size, data):
    if address == native.BASE + 0x59a3:
        # Coverage has its own native fixture; exercise both admitted and rejected results here.
        native.setreg('EFLAGS', (native.getreg('EFLAGS') & ~1) | int(covered))
        return_from_call(cpu)
    elif address == native.BASE + 0x5b92:
        points.append((native.getreg('DX'), native.getreg('DI') + 8))
        return_from_call(cpu)

native.cpu.hook_add(UC_HOOK_CODE, hook)
rng = random.Random(0x5b76)
rows = []
for case in range(512):
    x, y, heading = [rng.randrange(65536) for _ in range(3)]
    dx, dy = [rng.randrange(-2048, 2049) for _ in range(2)]
    hidden = case % 11 == 0
    covered = case % 13 != 0
    centre_y = (92, 120)[case % 2]
    shot_x, shot_y = (x + dx) & 65535, (y + dy) & 65535
    native.cpu.mem_write(native.STACK + 0xd98e, struct.pack('<HH', x, y))
    native.cpu.mem_write(native.STACK + 0xd9b0, struct.pack('<H', heading))
    native.cpu.mem_write(native.STACK + 0x6000, bytes(112))
    native.cpu.mem_write(native.STACK + 0x6007, bytes([8 if hidden else 0]))
    native.cpu.mem_write(native.STACK + 0x6008, struct.pack('<HH', shot_x, shot_y))
    native.write(0x5b80, struct.pack('<H', centre_y - 8 - 3))
    native.setreg('BP', 0x6000)
    native.setreg('BX', 0x31)
    native.setreg('DX', 0x070e)
    native.cpu.ctl_remove_cache(native.BASE, native.BASE + 65536)
    points.clear()
    native.call(0x5ac9)
    assert len(points) <= 1
    rows.append([x, y, heading, shot_x, shot_y, int(hidden), int(covered), centre_y,
                 int(bool(points)), *(points[0] if points else (0, 0))])
output = Path(__file__).resolve().parents[1] / 'tests/reference/missile_warning_samples.h'
output.write_text('''#pragma once

// Generated by tools/generate_missile_warning_reference.py; native 5AC9/5B76.
#include <array>

namespace darker::test_reference {
inline constexpr std::array<std::array<unsigned int, 11>, 512> missile_warning_samples{{
''' + '\n'.join('  {' + ', '.join(map(str, row)) + '},' for row in rows)
 + '\n}};\n} // namespace darker::test_reference\n')
print('Captured 512 native missile warning projections.')
